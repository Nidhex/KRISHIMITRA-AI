export function getTranslation(langCode: string, key: string): string {
  const translations = UI_TRANSLATIONS[langCode] || UI_TRANSLATIONS.hi;
  return translations[key] || UI_TRANSLATIONS.en[key] || key;
}

export function getLanguageOption(code: string): LanguageOption {
  return SUPPORTED_LANGUAGES.find(l => l.code === code) || SUPPORTED_LANGUAGES[0];
}
